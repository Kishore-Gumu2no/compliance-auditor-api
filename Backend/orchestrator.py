def ocr_ingestion_node(state: AuditState):
    extracted_text = state["raw_text"]
    for image in state["image_paths"]:
        with Image.open(image) as image_object:
            extracted_text += "\n\n" + pytesseract.image_to_string(image_object)
    return{"raw_text": extracted_text}

def pdf_ingestion_node(state: AuditState):
    full_text = [state["raw_text"]]
    for pdf in state["pdf_paths"]:
        with pdfplumber.open(pdf) as pdf_object:
            #region What is 'with' in the above line?
            """When you use python's 'open()' this is like a room which takes the file opens, reads and expects the programmer's close()
            command. Nevertheless, we've got another special room called 'with open()', just because the keyword 'with' is present, 
            you enter a special room to read file, it takes the file reads, processes and closes on itself the second your code finishes
            reading your file!!! If we use this, we wouldn't have to worry about MEMEORY LEAK, because in case the code crashes 'with' 
            statement mathematically guarantees that it will close the file and unlock the file before the program dies"""
            #endregion
            for page in pdf_object.pages:
                full_text.append(page.extract_text() or "")
            combined_text = "\n".join(full_text)
    return{"raw_text":combined_text}

def mask_data_node(state: AuditState):
    """In this node the worker's private data is redacted """
    text = state["raw_text"]
    scrubbed = mask_pii(text)
    return{"masked_text": scrubbed}

def ai_extraction_node(state: AuditState):
    #In this node we send the worker's masked data to the LLM strictly to get the same information in JSON format
    client = instructor.from_groq(Groq(api_key = my_key))
    #In the above line we are integrating instructor so that we can make sure that LLM cannot act probablistic and generate strictly according to data schema(RawAIExtraction)
    worker_data = state["masked_text"]
    system_prompt = "Extract: shift_date (YYYY-MM-DD), extracted_hours (int), extracted_minutes (int), rate (float), " \
                "actual_payout (float). Respond ONLY with valid JSON." \

    response = client.chat.completions.create(
        model = "groq/compound-mini",
        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": worker_data}
        ],
        response_model= RawAIExtraction,
        temperature = 0.0
    )
    ai_json_string = response.model_dump_json()
    #region What is .model_dump_json??
    """Since it is instructor who is handling the LLM generated data initially, we don't have to worry about massive complex 
    dictionary LLM generates, which consisits of layers of 'choice' and 'message'. Instructor directly gives us the required data
    which is in response --> choice[0] --> message --> content (response.choices[0].message.content). All we have to do is take
    the LLM's result which is in an object now because of instructor, and convert to JSON format through .model_dump_json"""
    #endregion

    
    return {"raw_ai_json": ai_json_string}
    #region What is ai_json_string?
    """An important thing to mind here is, ai_json_string holds data in JSON format being in STRING data type, which means 
       DATA_TYPE : string
       FORMAT FOLLOWED: JSON format
       WHAT DATA: The LLM's result when we give it worker's redacted information to recieve in JSON format"""
    #endregion

def data_cleaning_node(state):
    """In this node we make sure if the data is strictly in their own respective and favoured data type, the MAIN AGENDA of this node is:
       TO TAKE THE AMOUNT OF HOURS, MINUTES AND CONVERT TO DECIMAL, LET'S SAY IF IT WAS 8HR 30 MINS THIS NODE GIVES 8.5HR.
       this is easier for calculation purposes. """
    
    raw_data = RawAIExtraction.model_validate_json(state["raw_ai_json"])
    #region What is .model_validate_json??
    """.model_validate_json is a method from inherited BaseModel class, this method takes the text from AI, reads the data in JSON format
        line by line, then looks at the exact rules specified in WorkSession class and checks if the data(llm output) matches the rule book(WorkSession)
        class perfectly. The things happening under the hood is:
        1. First it reads raw JSON format text string and converts to basic dictionary.
        2. Takes the temporary dictionary and checks it against the class blueprint(WorkSession).
        3. If it checks, it converts the dictionary to a class object and returns it, if it doesnt check, it throws an error and stops the program"""
    #endregion
    
    total_hours = convert_time_to_decimal(raw_data.extracted_hours, raw_data.extracted_minutes)
    clean_dict = {
        "shift_date": str(raw_data.shift_date),
        "hours": float(total_hours),
        "rate": float(raw_data.rate),
        "actual_payout": float(raw_data.actual_payout)
    }
    return {"extracted_json": json.dumps(clean_dict)}


def calculation_node(state: AuditState):
    ai_data = state["extracted_json"]
    session = WorkSession.model_validate_json(ai_data)
    #region What is .model_validate_json??
    """.model_validate_json is a method from inherited BaseModel class, this method takes the text from AI, reads the data in JSON format
        line by line, then looks at the exact rules specified in WorkSession class and checks if the data(llm output) matches the rule book(WorkSession)
        class perfectly. The things happening under the hood is:
        1. First it reads raw JSON text string and converts to basic dictionary.
        2. Takes the temporary dictionary and checks it against the class blueprint(WorkSession).
        3. If it checks, it converts the dictionary to a class object and returns it, if it doesnt check, it throws an error and stops the program"""
    #endregion
    math_result = calculate_difference(session)
    log_record = { 
        "receipt_id" : math_result["receipt_id"],
        "shift_date": str(session.shift_date),
        "status": math_result["status"],
        "audit_details": {
            "hours_worked": float(session.hours),
            "rate": float(session.rate),
            "discrepancy": float(math_result["discrepancy"]),
            "Conclusion": math_result["status"]
        } }
    supabase_db.table("explainability_logs").upsert(log_record).execute()
    return {"final_status": math_result["status"], "receipt_id" : math_result["receipt_id"]}

def route_from_start(state:AuditState):
    if len(state["pdf_paths"])>0:
        return "pdf_ingestion"
    elif len(state["image_paths"])>0:
        return "ocr_ingestion"
    else:
        return "mask_data"

def route_from_pdf(state: AuditState):
    if len(state["image_paths"])>0:
        return "ocr_ingestion"
    else:
        return "mask_data"
workflow = StateGraph(AuditState) #Start the engine and memorize the the blueprint 'AuditState'
workflow.add_node("pdf_ingestion", pdf_ingestion_node)
workflow.add_node("ocr_ingestion", ocr_ingestion_node)
workflow.add_node("mask_data", mask_data_node)
workflow.add_node("ai_extraction", ai_extraction_node)
workflow.add_node("data_cleaning", data_cleaning_node)
workflow.add_node("calculation", calculation_node)
workflow.add_conditional_edges(START, route_from_start)
workflow.add_conditional_edges("pdf_ingestion", route_from_pdf)
workflow.add_edge("ocr_ingestion", "mask_data")
workflow.add_edge("mask_data", "ai_extraction")
workflow.add_edge("ai_extraction", "data_cleaning")
workflow.add_edge("data_cleaning", "calculation")
workflow.add_edge("calculation", END)
app = workflow.compile()
def run_audit(pdf_set: set, image_set:set):
    initial_state = {
        "pdf_paths": pdf_set,
        "image_paths": image_set,
        "raw_text" : "",
        "masked_text": "",
        "raw_ai_json": "",
        "extracted_json": "",
        "final_status": "",
        "receipt_id": ""
    }
    final_state = app.invoke(initial_state)
    return final_state

