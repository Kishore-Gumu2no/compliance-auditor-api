class WorkSession(BaseModel):
    #region The second Schema for our data and this one being used for mathematical calculation
    """Our math engine needs absolute perfection, this would be the second schema that the data will have to pass through after the 
    LLM generates data, because the first schema(schema 1) will be built specifically to talk with AI, if the data doesnt follow schema 1, it 
    accepts the mess, cleans and formats it, BUT OUR BACKEND ENGINE CANNOT ACCEPT A MESS AND CLEAN IT, it needs a strict blueprint to 
    accept the input and calculate the real deal """
    #endregion
    shift_date: date
    hours: Decimal
    rate: Decimal
    actual_payout: Decimal

    @field_validator("hours") #This our bouncer to check the logic of value stored in hours which is not supposed to be > 24 hrs
    def validate_hours(cls, value):
        if value > Decimal("24.00"):
            raise ValueError("Hours cannot exceed 24")
        return value


def calculate_difference(session):
    expected_payout = session.hours * session.rate
    difference = expected_payout - session.actual_payout
    search_query = f"What is the minimum wage for {session.shift_date.year}?"
    search_query_vector = list(embedding_model.embed([search_query]))[0]
    results = client.query_points(
        collection_name= "labor_laws",
        query= search_query_vector,
        limit=1
    ).points
    legal_wage = Decimal(results[0].payload["wage"])
    if ( legal_wage > session.rate):
        status = "Underpaid (Below Minimum Wage)"
    elif (legal_wage == session.rate):
        status = "Paid correctly"
    elif (legal_wage < session.rate):
        status = "Overpaid"

    log_data = f"{session.shift_date}_{difference}_{status}"
    #region What is above line?
    """In the above line we are using f-string. We use f-string when we need to extract data from the variable and perform
    any kind of work with it. In this scenario we are using f-strings in order to glue and store all the data inside 
    session.shift_date, difference and status into one variable. Why? Because we have three seperate pieces of data which holds 
    the information about changing the gig worker's working information and they session.shift_date, difference and status, we 
    are glueing all of them in one variable and then passing them to encode()."""
    #endregion
    reciept_hash = hashlib.sha256(log_data.encode()).hexdigest()
    #region Why .encode() and .hexdigest()?
    """1. hashlib's SHA256 engine takes the input, mathematically scarbles data into a unique 64-character string. There's
    a rule that needs to maintained, which is: INPUT SHOULD BE STRICTLY IN BINARY DATA (0s and 1s). In order to convert
    data from English characters to Binary data we use .encode().
    2. '.encode' takes the input and converts to Binary data and gives it to 'hashlib.sha256' to give the mathematically 
    scrambled maze, but the tricky part is it again returns in Binary format, which is not okay and unreadable.
    3. Here comes '.hexdigest()' which is takes binary data and converts to readable 64-character string using hexadecimal format.
    4. We are doing all of this because we do not want the data to be changed by the platform in case there's a law suit against 
    any gig worker."""
    #endregion

    return {"discrepancy": difference.quantize(Decimal('0.00')), "status": status, "receipt_id": reciept_hash}

